/** Every char code from 32 (space) to 126 ("~"), as single-character
 * strings, in ascending order. */
const PRINTABLE_ASCII: readonly string[] = Array.from({ length: 126 - 32 + 1 }, (_, i) =>
  String.fromCharCode(32 + i),
);

/** All char codes 32..126 plus "…" must have a glyph — this is asserted by
 * `glyphs-5x7.test.ts`, not re-checked here at runtime, since GLYPHS_5X7 is
 * a compile-time-authored constant, not computed. */
export const KNOWN_GLYPH_CHARS: readonly string[] = [...PRINTABLE_ASCII, "…"];

/**
 * Maps every character of `text` through `GLYPHS_5X7` (any character absent
 * from the table becomes "?"), then truncates to `maxChars`: if the mapped
 * string already fits, it is returned unchanged; otherwise the first
 * `maxChars - 1` mapped characters are kept and a trailing "…" is appended,
 * so the result is always exactly `maxChars` characters long when
 * truncation occurs.
 */
export function truncateLabel(text: string, maxChars: number): string {
  const mapped = Array.from(text)
    .map((ch) => (ch in GLYPHS_5X7 ? ch : "?"))
    .join("");
  if (mapped.length <= maxChars) {
    return mapped;
  }
  return mapped.slice(0, Math.max(0, maxChars - 1)) + "…";
}
