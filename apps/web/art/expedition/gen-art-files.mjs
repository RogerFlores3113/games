// Writes art-files.generated.ts: every PNG under public/expedition/sprites/,
// so the scenes request only sprites that exist.
//
//   npm run art:files --workspace apps/web
import fs from "node:fs";
import path from "node:path";

const web = path.resolve(import.meta.dirname, "../..");
const spritesDir = path.join(web, "public/expedition/sprites");
const out = path.join(web, "components/expedition/phaser/art/art-files.generated.ts");

const files = fs
  .readdirSync(spritesDir, { recursive: true })
  .map((f) => f.split(path.sep).join("/"))
  .filter((f) => f.endsWith(".png"))
  .sort();

const body = files.map((f) => `  "${f}",\n`).join("");
fs.writeFileSync(
  out,
  "// Generated by apps/web/art/expedition/gen-art-files.mjs: the sprite files\n" +
    "// present under apps/web/public/expedition/sprites/, relative to that folder.\n" +
    "// Lists only files on disk so the browser never requests a missing sprite.\n" +
    `export const ART_FILES: readonly string[] = [\n${body}];\n`,
);
console.log(`${files.length} sprite files -> ${path.relative(web, out)}`);
